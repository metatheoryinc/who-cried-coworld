/*
 * Generates the two artifacts the prototype page is allowed to load.
 * Run: node build-fixtures.mjs
 *
 * The page never imports episode-source.mjs. If it did, the live demo would be a
 * lie: it would hold every private event and merely decline to draw them.
 */
import fs from 'node:fs';
import path from 'node:path';
import { EPISODE, EVENTS } from './episode-source.mjs';
import { projectLive, projectReplay, census } from './project.mjs';

const REPLAY_ALLOWLIST = [
  'discarded_bids', 'confessional', 'wolf_chat', 'night_choices', 'failures', 'roles',
];

const live = projectLive(EPISODE, EVENTS, EPISODE.liveHorizon);
const replay = projectReplay(EPISODE, EVENTS, REPLAY_ALLOWLIST);

// Guard rails. A projection that fails these is not evidence of anything.
const assert = (ok, msg) => {
  if (!ok) { console.error('FAIL  ' + msg); process.exitCode = 1; } else console.log('ok    ' + msg);
};
const liveText = JSON.stringify(live);

assert(live.events.every(e => e.reveal === 'public'), 'live projection carries only public events');
assert(!live.seats.some(s => 'role' in s), 'live roster carries no roles');
assert(live.events.every((e, i) => e.seq === i + 1), 'live sequence is dense, so gaps cannot be counted');
assert(!/wolf faction|confessional/i.test(liveText), 'live bytes contain no private vocabulary');

const leaked = EVENTS
  .filter(e => e.audience !== 'public' && typeof e.text === 'string' && e.text.length > 12)
  .filter(e => liveText.includes(e.text));
assert(leaked.length === 0, 'live bytes contain no private authored text (' + leaked.length + ' leaks)');

assert(replay.events.length > live.events.length, 'replay export is a superset of public material');
assert(replay.complete === true, 'replay is marked complete');
assert(replay.seats.every(s => 'role' in s), 'replay roster carries roles, so the spoiler toggle is presentation only');

/* Sentinel: prove the projectors CONSTRUCT payloads rather than copy them.
   A shallow allowlist would let these nested extras ride into the artifacts. */
const SENTINEL = 'SENTINEL_MUST_NOT_SURVIVE';
const spike = (o) => (o && typeof o === 'object' ? { ...o, smuggled: SENTINEL } : o);
const spiked = EVENTS.map(e => ({
  ...e,
  smuggled: SENTINEL,
  ...(e.items   ? { items:   e.items.map(spike) }   : {}),
  ...(e.ballots ? { ballots: e.ballots.map(spike) } : {}),
  ...(e.actions ? { actions: e.actions.map(spike) } : {}),
  ...(e.scores  ? { scores:  e.scores.map(spike) }  : {}),
}));
const spikedEpisode = { ...EPISODE, seats: EPISODE.seats.map(spike) };
const spikedLive = JSON.stringify(projectLive(spikedEpisode, spiked, EPISODE.liveHorizon));
const spikedReplay = JSON.stringify(projectReplay(spikedEpisode, spiked, REPLAY_ALLOWLIST));
assert(!spikedLive.includes(SENTINEL), 'injected nested field does not survive into the live projection');
assert(!spikedReplay.includes(SENTINEL), 'injected nested field does not survive into the replay export');
assert(spikedReplay.includes('Coriander is reading you'), 'the sentinel run still produced a real projection');

const dir = path.join(import.meta.dirname, 'fixtures');
fs.mkdirSync(dir, { recursive: true });
const emit = (file, name, value) => {
  fs.writeFileSync(path.join(dir, file),
    '/* GENERATED by build-fixtures.mjs - do not edit. Source: episode-source.mjs */\n' +
    'const ' + name + ' = ' + JSON.stringify(value, null, 2) + ';\n');
};
emit('live-public.js', 'LIVE_PUBLIC', live);
emit('replay-export.js', 'REPLAY_EXPORT', replay);

console.log('');
console.log('live   ' + JSON.stringify(census(live)));
console.log('replay ' + JSON.stringify(census(replay)));
